import { defineBalanceEntry } from './define';
import type { BalanceUnit } from './types';

/**
 * 粗粒度チーム、組織集約、業界比較の調整値。
 *
 * 式そのものは `src/sim/orgscale/` に残し、ここでは初期分布、係数、
 * clamp 境界、ランキング境界だけを型付きで管理する。既存の乱数消費順、
 * 丸め位置、表示用コンテンツ定義は変更しない。
 */

type EntryConfig = {
  id: string;
  value: number;
  unit: BalanceUnit;
  min: number;
  max: number;
  label: string;
  description: string;
  tags?: readonly string[];
  integer?: boolean;
};

function coarseEntry(config: EntryConfig) {
  return defineBalanceEntry({
    id: config.id,
    value: config.value,
    unit: config.unit,
    allowedRange: { min: config.min, max: config.max },
    label: config.label,
    description: config.description,
    tags: ['coarse-team', ...(config.tags ?? [])],
    derived: false,
    ...(config.integer ? { integer: true } : {}),
  });
}

