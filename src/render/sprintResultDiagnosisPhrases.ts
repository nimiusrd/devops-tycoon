/** 既知の診断文を文節へ分解する。未知文は読点・句点の直後だけで分割する。 */
export function sprintResultDiagnosisPhrases(diagnosis: string): readonly string[] {
  const known = SPRINT_RESULT_DIAGNOSIS_PHRASES[diagnosis];
  if (known) return known;
  const split = diagnosis
    .split(/(?<=、)|(?<=。)/)
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
  return split.length > 0 ? split : [diagnosis];
}

/** テスト用: 公式診断文がすべてマップされているか検証する。 */
export function sprintResultDiagnosisPhraseKeys(): readonly string[] {
  return Object.keys(SPRINT_RESULT_DIAGNOSIS_PHRASES);
}
